def desc_line_count(item) -> int:
    n = 1
    if (getattr(item, "couleur", "") or "").strip():
        n += 1
    if (getattr(item, "taille", "") or "").strip():
        n += 1
    return n


def row_height(item) -> float:
    return ROW_H_BASE + (desc_line_count(item) - 1) * LINE_PITCH


def is_magasin(card) -> bool:
    mode = (getattr(card, "livraison_mode", "") or "").strip().lower()
    return mode == MODE_MAGASIN


def is_single_line_ship(card) -> bool:
    mode = (getattr(card, "livraison_mode", "") or "").strip().lower()
    return mode in {MODE_MAGASIN, MODE_DOMICILE}


def addr_shift(card) -> float:
    return MAGASIN_DY if is_single_line_ship(card) else 0.0


def article_shift(card) -> float:
    return 0.0 if is_single_line_ship(card) else -MAGASIN_DY


def row_bands(items, dy: float = 0.0):
    rows = list(items or ())[:MAX_ROWS]
    if not rows:
        return []
    y_top = ROW_TOP + dy
    bands = []
    for item in rows:
        y_bot = y_top + row_height(item)
        bands.append((y_top, y_bot, item))
        y_top = y_bot - ROW_JOIN
    return bands


def table_shift(items) -> float:
    bands = row_bands(items)
    if not bands:
        return 0.0
    return bands[-1][1] - (ROW_TOP + ROW_H_BASE)


def middle_shift(card) -> float:
    return addr_shift(card) + table_shift(getattr(card, "items", ()))


def num_y(y_top: float, y_bot: float) -> float:
    return (y_top + y_bot) / 2.0 + NUM_FROM_MID
