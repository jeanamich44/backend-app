def shifted_fills(fills, dy: float):
    if not dy:
        return fills
    return tuple((x0, y0 + dy, x1, y1 + dy, color) for x0, y0, x1, y1, color in fills)


def shifted_rule(rule, dy: float):
    if not dy:
        return rule
    x0, y, x1, w = rule
    return (x0, y + dy, x1, w)
