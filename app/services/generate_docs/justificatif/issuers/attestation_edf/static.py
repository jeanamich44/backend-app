def _default(field):
    return getattr(texts, field.upper(), '')


def draw(c, doc):
    vis = doc.visible
    card = doc.card
    last_color = None
    for field, group in groupby(SPANS, key=lambda s: s[6]):
        parts = list(group)
        y0, font0, size0, color0, layer0, glyphs0, _ = parts[0]
        if not _LAYER_OK[layer0](vis):
            continue
        if field is None:
            for y, font, size, color, layer, glyphs, _f in parts:
                if color != last_color:
                    fill(c, color)
                    last_color = color
                draw_glyphs(c, y, glyphs, _FONTS[font], size)
            continue
        default = _default(field)
        text = getattr(card, field, default)
        if not text:
            continue
        if text == default:
            for y, font, size, color, layer, glyphs, _f in parts:
                if color != last_color:
                    fill(c, color)
                    last_color = color
                draw_glyphs(c, y, glyphs, _FONTS[font], size)
            continue
        if color0 != last_color:
            fill(c, color0)
            last_color = color0
        draw_string(c, glyphs0[0][1], y0, text, _FONTS[font0], size0)
